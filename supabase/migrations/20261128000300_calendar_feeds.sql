-- =============================================================================
-- DosarIA — private calendar link (ICS feed) per person
-- =============================================================================
-- A person can create one secret calendar link per firm and subscribe to it
-- in Google Calendar or Outlook. The feed contains:
--   * upcoming hearings of their cases (from the latest complete snapshot), and
--   * their confirmed deadlines,
-- for the same cases they get alerts for: assigned to them as lawyer or
-- assistant, or followed by them while they may read them (admin).
--
-- Privacy:
--   * Only a SHA-256 hash of the link's token is stored. The full link is
--     shown once; a lost link is replaced, which revokes the old one.
--   * Calendar providers fetch and store the feed, so it carries the minimum:
--     case number and court name, never case titles, party names or the
--     court's text. Deadline titles are not included either.
--   * The feed is read only by the server (service role) after the token is
--     verified; no API role can call the feed function.
-- =============================================================================

create table public.calendar_feeds (
  id               uuid primary key default gen_random_uuid(),
  organization_id  uuid not null,
  user_id          uuid not null,
  token_hash       text not null,
  created_at       timestamptz not null default now(),
  last_used_at     timestamptz,
  revoked_at       timestamptz,
  constraint calendar_feeds_member_fk
    foreign key (organization_id, user_id)
    references public.organization_memberships (organization_id, user_id) on delete cascade,
  constraint calendar_feeds_token_hash_key unique (token_hash),
  constraint calendar_feeds_token_hash_format check (token_hash ~ '^[0-9a-f]{64}$')
);
-- At most one active link per person per firm.
create unique index calendar_feeds_active_key on public.calendar_feeds (organization_id, user_id)
  where revoked_at is null;

revoke all on table public.calendar_feeds from anon, authenticated;
grant select, insert, update, delete on table public.calendar_feeds to service_role;
grant select (id, organization_id, user_id, created_at, last_used_at, revoked_at) on public.calendar_feeds to authenticated;
grant insert (organization_id, user_id, token_hash) on public.calendar_feeds to authenticated;
grant update (revoked_at) on public.calendar_feeds to authenticated;

alter table public.calendar_feeds enable row level security;

create policy calendar_feeds_select_own on public.calendar_feeds
  for select to authenticated
  using (user_id = (select auth.uid()));
create policy calendar_feeds_insert_own on public.calendar_feeds
  for insert to authenticated
  with check (user_id = (select auth.uid()) and organization_id in (select private.member_org_ids()));
create policy calendar_feeds_update_own on public.calendar_feeds
  for update to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

-- Users may only create a fresh link and revoke one; times are the server's.
create or replace function private.guard_calendar_feeds()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if private.is_privileged_role() then
    return new;
  end if;
  if tg_op = 'INSERT' then
    new.user_id      := (select auth.uid());
    new.created_at   := now();
    new.last_used_at := null;
    new.revoked_at   := null;
    return new;
  end if;
  if old.revoked_at is not null or new.revoked_at is null then
    raise exception 'a calendar link can only be revoked once' using errcode = '42501';
  end if;
  new.revoked_at := now();
  return new;
end;
$$;

create trigger guard_calendar_feeds before insert or update on public.calendar_feeds
  for each row execute function private.guard_calendar_feeds();

create or replace function private.audit_calendar_feeds()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    perform private.write_audit(new.organization_id, 'calendar.link_created', 'membership', null,
      jsonb_build_object('feed_id', new.id, 'user_id', new.user_id));
  elsif new.revoked_at is not null and old.revoked_at is null then
    perform private.write_audit(new.organization_id, 'calendar.link_revoked', 'membership', null,
      jsonb_build_object('feed_id', new.id, 'user_id', new.user_id));
  end if;
  return new;
end;
$$;

create trigger audit_calendar_feeds after insert or update of revoked_at on public.calendar_feeds
  for each row execute function private.audit_calendar_feeds();

-- ---------------------------------------------------------------------------
-- Replace the caller's link in one step (SECURITY INVOKER: RLS and the guard
-- apply). The token is generated by the server; only its hash arrives here.
-- ---------------------------------------------------------------------------
create or replace function public.replace_calendar_feed(p_organization_id uuid, p_token_hash text)
returns uuid
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_id uuid;
begin
  update public.calendar_feeds
     set revoked_at = now()
   where organization_id = p_organization_id
     and user_id = (select auth.uid())
     and revoked_at is null;

  insert into public.calendar_feeds (organization_id, user_id, token_hash)
  values (p_organization_id, (select auth.uid()), p_token_hash)
  returning id into v_id;
  return v_id;
end;
$$;

revoke execute on function public.replace_calendar_feed(uuid, text) from public, anon;
grant execute on function public.replace_calendar_feed(uuid, text) to authenticated;

-- ---------------------------------------------------------------------------
-- The feed. Service role only: the route handler hashes the token from the
-- URL and passes the hash. Returns nothing for an unknown or revoked link, or
-- when the person is no longer an active member.
-- ---------------------------------------------------------------------------
create or replace function public.calendar_feed(p_token_hash text)
returns table (
  item_kind          text,
  item_key           text,
  case_id            uuid,
  court_case_number  text,
  court_name         text,
  item_date          date,
  item_time          text
)
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_org   uuid;
  v_user  uuid;
  v_role  public.membership_role;
  v_today date := (now() at time zone 'Europe/Bucharest')::date;
begin
  if not private.is_privileged_role() then
    raise exception 'privileged operation' using errcode = '42501';
  end if;
  if p_token_hash is null or p_token_hash !~ '^[0-9a-f]{64}$' then
    return;
  end if;

  select f.organization_id, f.user_id, m.role into v_org, v_user, v_role
  from public.calendar_feeds f
  join public.organization_memberships m
    on m.organization_id = f.organization_id and m.user_id = f.user_id and m.status = 'active'
  where f.token_hash = p_token_hash and f.revoked_at is null;
  if v_org is null then
    return;
  end if;

  update public.calendar_feeds
     set last_used_at = now()
   where token_hash = p_token_hash
     and (last_used_at is null or last_used_at < now() - interval '1 hour');

  -- Marker row: the link is valid (lets the caller tell "no events" from "no such link").
  return query select 'feed'::text, null::text, null::uuid, null::text, null::text, null::date, null::text;

  return query
  with my_cases as (
    select c.id, c.court_case_number, c.court_name
    from public.cases c
    where c.organization_id = v_org
      and c.status <> 'archived'
      and (
        c.assigned_user_id = v_user
        or c.assigned_assistant_id = v_user
        or (v_role = 'admin' and exists (
              select 1 from public.case_followers cf where cf.case_id = c.id and cf.user_id = v_user))
      )
  ),
  latest as (
    select distinct on (s.case_id) s.case_id, s.data
    from public.case_snapshots s
    join my_cases mc on mc.id = s.case_id
    where s.completeness = 'complete'
    order by s.case_id, s.created_at desc
  ),
  hearings as (
    select l.case_id, (h ->> 'date')::date as d, nullif(h ->> 'time', '') as t
    from latest l
    cross join lateral jsonb_array_elements(coalesce(l.data -> 'hearings', '[]'::jsonb)) as h
    where (h ->> 'date') ~ '^\d{4}-\d{2}-\d{2}$'
      and (h ->> 'solutionType') is null
  )
  select 'hearing'::text, mc.id::text || ':' || h.d::text || ':' || coalesce(h.t, ''), mc.id,
         mc.court_case_number, mc.court_name, h.d, h.t
  from hearings h join my_cases mc on mc.id = h.case_id
  where h.d >= v_today - 30 and h.d <= v_today + 400
  union all
  select 'deadline'::text, r.id::text, mc.id, mc.court_case_number, mc.court_name, r.due_date, null::text
  from public.deadline_reminders r join my_cases mc on mc.id = r.case_id
  where r.status = 'confirmed' and r.due_date >= v_today - 30 and r.due_date <= v_today + 400
  order by 6, 7 nulls first
  limit 500;
end;
$$;

revoke execute on function public.calendar_feed(text) from public, anon, authenticated;
grant execute on function public.calendar_feed(text) to service_role;

revoke execute on function private.guard_calendar_feeds(), private.audit_calendar_feeds()
  from public, anon, authenticated;
