"use client";

import { useActionState, useState, useTransition } from "react";
import { AlertCircle, CheckCircle2 } from "lucide-react";
import { confirmMfaEnrollmentAction, startMfaEnrollmentAction } from "@/app/actions/mfa";
import { SubmitButton } from "@/components/app/action-form";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import type { Dictionary } from "@/i18n";
import type { ActionResult } from "@/lib/errors";
import type { MfaEnrollment } from "@/lib/shared-types";

/**
 * Adding an authenticator app: show the QR code and the key once, then
 * confirm with the first code. Nothing is stored in the browser.
 */
export function MfaSetup({ s, hasFactors }: { s: Dictionary["mfa"]; hasFactors: boolean }) {
  const [enrollment, setEnrollment] = useState<MfaEnrollment | null>(null);
  const [startError, setStartError] = useState<string | null>(null);
  const [starting, startTransition] = useTransition();
  const [confirmed, confirmAction] = useActionState<ActionResult | null, FormData>(confirmMfaEnrollmentAction, null);

  if (confirmed?.ok) {
    return (
      <p role="status" className="flex items-start gap-2 text-sm text-emerald-700 dark:text-emerald-400" data-testid="mfa-enabled">
        <CheckCircle2 className="mt-0.5 size-4 shrink-0" aria-hidden />
        <span>{confirmed.message}</span>
      </p>
    );
  }

  if (!enrollment) {
    return (
      <div className="grid gap-2">
        <div>
          <Button
            type="button"
            variant={hasFactors ? "outline" : "default"}
            disabled={starting}
            onClick={() =>
              startTransition(async () => {
                const r = await startMfaEnrollmentAction();
                if (r.ok && r.data) {
                  setEnrollment(r.data);
                  setStartError(null);
                } else if (!r.ok) {
                  setStartError(r.error);
                }
              })
            }
          >
            {hasFactors ? s.addDevice : s.turnOn}
          </Button>
        </div>
        {startError && (
          <p role="alert" className="flex items-start gap-2 text-sm text-destructive">
            <AlertCircle className="mt-0.5 size-4 shrink-0" aria-hidden />
            <span>{startError}</span>
          </p>
        )}
      </div>
    );
  }

  return (
    <div className="grid gap-4 rounded-md border p-4" data-testid="mfa-setup">
      <div className="grid gap-2">
        <p className="text-sm font-medium">{s.scan}</p>
        {/* eslint-disable-next-line @next/next/no-img-element -- a data: URL generated by Supabase Auth */}
        <img src={enrollment.qrCode} alt={s.qrAlt} width={180} height={180} className="rounded bg-white p-2" />
        <p className="text-xs text-muted-foreground">{s.manual}</p>
        <code className="w-fit rounded bg-muted px-2 py-1 font-mono text-xs break-all select-all" data-testid="mfa-secret">
          {enrollment.secret}
        </code>
      </div>
      <form action={confirmAction} className="grid gap-2" noValidate>
        <input type="hidden" name="factorId" value={enrollment.factorId} />
        <Label htmlFor="mfa-setup-code">{s.enterCode}</Label>
        <Input
          id="mfa-setup-code"
          name="code"
          inputMode="numeric"
          autoComplete="one-time-code"
          pattern="[0-9]{6}"
          maxLength={6}
          className="w-36 font-mono tracking-widest"
          required
        />
        {confirmed && !confirmed.ok && (
          <p role="alert" className="flex items-start gap-2 text-sm text-destructive">
            <AlertCircle className="mt-0.5 size-4 shrink-0" aria-hidden />
            <span>{confirmed.error}</span>
          </p>
        )}
        <div className="flex gap-2">
          <SubmitButton>{s.confirm}</SubmitButton>
          <Button type="button" variant="ghost" onClick={() => setEnrollment(null)}>
            {s.cancel}
          </Button>
        </div>
      </form>
    </div>
  );
}
