#!/usr/bin/env node
/**
 * Writes .env.local for LOCAL development from `supabase status -o env`.
 * Keys are written to the (git-ignored) file and never printed.
 */
import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const raw = execSync("npx supabase status -o env", { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
const status = {};
for (const line of raw.split(/\r?\n/)) {
  const m = line.match(/^([A-Z_]+)="?(.*?)"?$/);
  if (m) status[m[1]] = m[2];
}

const url = status.API_URL;
const publishable = status.PUBLISHABLE_KEY || status.ANON_KEY;
const secret = status.SECRET_KEY || status.SERVICE_ROLE_KEY;
if (!url || !publishable || !secret) {
  console.error("Could not read local Supabase status. Is `npx supabase start` running?");
  process.exit(1);
}
if (!/^http:\/\/(127\.0\.0\.1|localhost)(:\d+)?$/.test(url)) {
  console.error("Refusing to write .env.local: Supabase API URL is not local.");
  process.exit(1);
}

const managed = {
  APP_URL: "http://localhost:3000",
  SUPABASE_URL: url,
  SUPABASE_PUBLISHABLE_KEY: publishable,
  SUPABASE_SECRET_KEY: secret,
  COURT_DATA_PROVIDER: "mock",
  MOCK_COURT_LATENCY_MS: "300",
};

// Preserve any other variables the developer already set.
const existing = existsSync(".env.local") ? readFileSync(".env.local", "utf8") : "";
const kept = existing
  .split(/\r?\n/)
  .filter((l) => l.trim() && !Object.keys(managed).some((k) => l.startsWith(`${k}=`)));

writeFileSync(
  ".env.local",
  ["# Generated by scripts/local-env.mjs for LOCAL development only. Do not commit.", ...kept.filter((l) => !l.startsWith("# Generated")), ...Object.entries(managed).map(([k, v]) => `${k}=${v}`), ""].join("\n"),
);
console.log(`Wrote .env.local (SUPABASE_URL=${url}; keys hidden).`);
